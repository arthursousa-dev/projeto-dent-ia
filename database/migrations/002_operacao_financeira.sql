CREATE TABLE lancamento_financeiro (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data DATE NOT NULL, tipo tipo_lancamento NOT NULL,
    descricao VARCHAR(250) NOT NULL CHECK (btrim(descricao) <> ''),
    valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
    id_categoria INT NOT NULL,
    id_usuario INT NOT NULL REFERENCES usuarios ON DELETE RESTRICT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (id_categoria,tipo) REFERENCES categoria_lancamento (id,tipo) ON DELETE RESTRICT
);
CREATE INDEX idx_lancamento_data ON lancamento_financeiro(data);
CREATE INDEX idx_lancamento_categoria ON lancamento_financeiro(id_categoria,tipo);
CREATE INDEX idx_lancamento_usuario ON lancamento_financeiro(id_usuario);
CREATE TABLE evolucao_clinica (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_prontuario INT NOT NULL REFERENCES prontuarios ON DELETE RESTRICT,
    id_dentista INT NOT NULL, id_procedimento INT NOT NULL,
    id_agendamento INT UNIQUE REFERENCES agendamentos ON DELETE RESTRICT,
    observacoes TEXT NOT NULL CHECK (btrim(observacoes) <> ''),
    retorno DATE, registrado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (id_dentista,id_procedimento) REFERENCES dentista_procedimentos ON DELETE RESTRICT
);
CREATE INDEX idx_evolucao_prontuario ON evolucao_clinica(id_prontuario);
CREATE INDEX idx_evolucao_dentista_procedimento ON evolucao_clinica(id_dentista,id_procedimento);
CREATE TABLE evolucao_dente (
    id_evolucao INT NOT NULL REFERENCES evolucao_clinica ON DELETE RESTRICT,
    id_dente INT NOT NULL REFERENCES odontograma_dentes ON DELETE RESTRICT,
    PRIMARY KEY (id_evolucao,id_dente)
);
CREATE INDEX idx_evolucao_dente ON evolucao_dente(id_dente);
CREATE TABLE recuperacao_senha (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL REFERENCES usuarios ON DELETE RESTRICT,
    token_hash CHAR(64) UNIQUE,
    solicitado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    expira_em TIMESTAMPTZ, utilizado_em TIMESTAMPTZ,
    CHECK ((token_hash IS NULL) = (expira_em IS NULL))
);
CREATE INDEX idx_recuperacao_usuario ON recuperacao_senha(id_usuario);

CREATE FUNCTION validar_sobreposicao_agenda() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE duracao INT; chave BIGINT;
BEGIN
    IF NEW.status = 'Cancelado' THEN RETURN NEW; END IF;
    FOR chave IN SELECT k FROM unnest(ARRAY[1000000000::bigint+NEW.id_dentista,
        2000000000::bigint+NEW.id_paciente,3000000000::bigint+NEW.id_sala]) k ORDER BY k LOOP
        PERFORM pg_advisory_xact_lock(chave);
    END LOOP;
    SELECT duracao_min INTO duracao FROM procedimentos WHERE id=NEW.id_procedimento;
    IF EXISTS (
        SELECT 1 FROM agendamentos a JOIN procedimentos p ON p.id=a.id_procedimento
        WHERE a.id <> NEW.id AND a.status <> 'Cancelado'
          AND (a.id_dentista=NEW.id_dentista OR a.id_paciente=NEW.id_paciente OR a.id_sala=NEW.id_sala)
          AND tsrange(a.data+a.hora,a.data+a.hora+make_interval(mins=>p.duracao_min),'[)') &&
              tsrange(NEW.data+NEW.hora,NEW.data+NEW.hora+make_interval(mins=>duracao),'[)')
    ) THEN RAISE EXCEPTION 'Horário sobreposto para dentista, paciente ou sala' USING ERRCODE='23505'; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER agenda_sobreposicao BEFORE INSERT OR UPDATE ON agendamentos
FOR EACH ROW EXECUTE FUNCTION validar_sobreposicao_agenda();

CREATE FUNCTION validar_evolucao() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.id_agendamento IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM agendamentos a JOIN prontuarios pr ON pr.id_paciente=a.id_paciente
        WHERE a.id=NEW.id_agendamento AND pr.id=NEW.id_prontuario
        AND a.id_dentista=NEW.id_dentista AND a.id_procedimento=NEW.id_procedimento
    ) THEN RAISE EXCEPTION 'Evolução incompatível com agendamento' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER evolucao_agendamento BEFORE INSERT OR UPDATE ON evolucao_clinica
FOR EACH ROW EXECUTE FUNCTION validar_evolucao();
CREATE FUNCTION validar_dente_evolucao() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM evolucao_clinica e JOIN odontograma_dentes d ON d.id_prontuario=e.id_prontuario
        WHERE e.id=NEW.id_evolucao AND d.id=NEW.id_dente) THEN
        RAISE EXCEPTION 'Dente de outro prontuário' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER evolucao_dente_prontuario BEFORE INSERT OR UPDATE ON evolucao_dente
FOR EACH ROW EXECUTE FUNCTION validar_dente_evolucao();

CREATE VIEW vw_movimentos_financeiros AS
SELECT -pg.id AS id, pg.pago_em::date AS data, 'Receita'::text AS tipo,
       pr.nome || ' — ' || pp.nome AS descricao, pg.valor, pg.id_agendamento,
       'pagamento'::text AS origem, fp.nome AS forma_pagamento
FROM pagamento pg JOIN agendamentos a ON a.id=pg.id_agendamento
JOIN procedimentos pr ON pr.id=a.id_procedimento JOIN pacientes pac ON pac.id=a.id_paciente
JOIN pessoa pp ON pp.id=pac.id_pessoa JOIN forma_pagamento fp ON fp.id=pg.id_forma_pagamento
WHERE pg.pago_em IS NOT NULL
UNION ALL
SELECT l.id,l.data,l.tipo::text,l.descricao,l.valor,NULL,'manual',NULL
FROM lancamento_financeiro l;

CREATE VIEW vw_resumo_financeiro_mensal AS
WITH meses AS (
    SELECT date_trunc('month',data)::date AS mes FROM vw_movimentos_financeiros
    UNION SELECT date_trunc('month',data)::date FROM agendamentos
), caixa AS (
    SELECT date_trunc('month',data)::date AS mes,
           COALESCE(sum(valor) FILTER (WHERE tipo='Receita'),0) AS receita,
           COALESCE(sum(valor) FILTER (WHERE tipo='Despesa'),0) AS despesas
    FROM vw_movimentos_financeiros GROUP BY 1
), producao AS (
    SELECT date_trunc('month',data)::date AS mes,
           count(*) FILTER (WHERE status='Concluída') AS procedimentos,
           COALESCE(sum(valor) FILTER (WHERE status='Concluída'),0) AS valor_producao
    FROM agendamentos GROUP BY 1
)
SELECT extract(year FROM m.mes)::int AS ano, extract(month FROM m.mes)::int AS mes_num,
       COALESCE(c.receita,0) AS receita, COALESCE(c.despesas,0) AS despesas,
       COALESCE(p.procedimentos,0) AS procedimentos, COALESCE(p.valor_producao,0) AS valor_producao
FROM meses m LEFT JOIN caixa c USING (mes) LEFT JOIN producao p USING (mes);
COMMENT ON VIEW vw_movimentos_financeiros IS 'Caixa: pagamentos confirmados mais lançamentos avulsos; sem dupla contagem.';
COMMENT ON VIEW vw_resumo_financeiro_mensal IS 'Indicadores operacionais calculados. Faturamento_mensal guarda fechamentos históricos.';
COMMIT;
