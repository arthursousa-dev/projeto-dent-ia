    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    tipo tipo_lancamento NOT NULL,
    UNIQUE (id, tipo)
);
INSERT INTO categoria_lancamento (nome,tipo) VALUES
