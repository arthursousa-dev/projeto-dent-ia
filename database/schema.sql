CREATE FUNCTION validar_cpf(cpf TEXT) RETURNS BOOLEAN
LANGUAGE plpgsql IMMUTABLE STRICT AS $$
DECLARE soma INT; digito INT; i INT; etapa INT;
BEGIN
    IF cpf !~ '^[0-9]{11}$' OR cpf = repeat(substr(cpf, 1, 1), 11) THEN RETURN false; END IF;
    FOR etapa IN 10..11 LOOP
        soma := 0;
        FOR i IN 1..etapa-1 LOOP
            soma := soma + substr(cpf, i, 1)::int * (etapa + 1 - i);
        END LOOP;
        digito := (soma * 10) % 11;
        IF digito = 10 THEN digito := 0; END IF;
        IF digito <> substr(cpf, etapa, 1)::int THEN RETURN false; END IF;
    END LOOP;
    RETURN true;
END $$;

