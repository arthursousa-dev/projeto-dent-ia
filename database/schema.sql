CREATE TABLE cidade (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL, uf CHAR(2) NOT NULL REFERENCES estado ON DELETE RESTRICT,
    UNIQUE (nome, uf)
);
CREATE TABLE endereco (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    logradouro VARCHAR(200), numero VARCHAR(20), complemento VARCHAR(100), bairro VARCHAR(100),
    cep VARCHAR(8) CHECK (cep ~ '^[0-9]{8}$'),
    id_cidade INT REFERENCES cidade ON DELETE RESTRICT,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE pessoa (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL CHECK (btrim(nome) <> ''),
    cpf VARCHAR(11) NOT NULL UNIQUE CHECK (validar_cpf(cpf)),
    rg VARCHAR(20), nascimento DATE, sexo CHAR(1) CHECK (sexo IN ('M','F','O')),
    email VARCHAR(150) CHECK (email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE usuarios (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pessoa INT NOT NULL UNIQUE REFERENCES pessoa ON DELETE RESTRICT,
    email VARCHAR(150) NOT NULL UNIQUE CHECK (email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'),
    senha_hash VARCHAR(255) NOT NULL, tipo tipo_usuario NOT NULL,
    status status_usuario NOT NULL DEFAULT 'ativo',
    tentativas_login SMALLINT NOT NULL DEFAULT 0 CHECK (tentativas_login >= 0),
    bloqueado_ate TIMESTAMPTZ, criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
