    id_especialidade INT NOT NULL REFERENCES especialidade ON DELETE RESTRICT,
    id_sala INT REFERENCES sala ON DELETE RESTRICT,
    titulacao VARCHAR(150), faculdade VARCHAR(150), ano_formatura SMALLINT CHECK (ano_formatura BETWEEN 1900 AND 2200),
    admissao DATE, cor VARCHAR(7) NOT NULL DEFAULT '#00c9a7' CHECK (cor ~ '^#[0-9A-Fa-f]{6}$'),
    status status_usuario NOT NULL DEFAULT 'ativo', criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
