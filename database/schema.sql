CREATE FUNCTION formatar_cpf(TEXT) RETURNS TEXT LANGUAGE sql IMMUTABLE STRICT AS $$
    SELECT regexp_replace($1, '^([0-9]{3})([0-9]{3})([0-9]{3})([0-9]{2})$', '\1.\2.\3-\4');
$$;
CREATE FUNCTION formatar_telefone(TEXT) RETURNS TEXT LANGUAGE sql IMMUTABLE STRICT AS $$
    SELECT regexp_replace($1, '^([0-9]{2})([0-9]{4,5})([0-9]{4})$', '(\1) \2-\3');
$$;
CREATE VIEW vw_enderecos AS
SELECT e.id, concat_ws(', ', e.logradouro, e.numero) AS endereco,
       e.bairro, c.nome AS cidade, c.uf AS estado,
       regexp_replace(e.cep, '^([0-9]{5})([0-9]{3})$', '\1-\2') AS cep
FROM endereco e LEFT JOIN cidade c ON c.id = e.id_cidade;
CREATE VIEW vw_usuarios AS
SELECT u.id, u.email, u.senha_hash AS senha, u.tipo, p.nome, formatar_cpf(p.cpf) AS cpf,
       (SELECT formatar_telefone(t.numero) FROM telefone t WHERE t.id_pessoa=p.id AND t.finalidade='principal') AS telefone,
       to_char(p.nascimento,'YYYY-MM-DD') AS nascimento,
       CASE u.tipo WHEN 'dono' THEN 'Proprietário' WHEN 'dentista' THEN 'Dentista'
       WHEN 'recepcionista' THEN 'Recepcionista' ELSE 'Paciente' END AS cargo,
       u.status, u.criado_em::timestamp AS criado_em
FROM usuarios u JOIN pessoa p ON p.id=u.id_pessoa;
CREATE VIEW vw_pacientes AS
SELECT pac.id, u.id AS id_usuario, p.nome, formatar_cpf(p.cpf) AS cpf, p.rg, p.email,
       (SELECT formatar_telefone(t.numero) FROM telefone t WHERE t.id_pessoa=p.id AND t.finalidade='principal') AS telefone,
       (SELECT formatar_telefone(t.numero) FROM telefone t WHERE t.id_pessoa=p.id AND t.finalidade='emergencia' ORDER BY t.id LIMIT 1) AS telefone_emergencia,
       to_char(p.nascimento,'YYYY-MM-DD') AS nascimento, p.sexo, pac.estado_civil, pac.profissao,
       pl.nome AS plano, pac.numero_carteirinha, e.endereco, e.bairro, e.cidade, e.estado, e.cep,
       (SELECT string_agg(h.descricao, ', ' ORDER BY h.id) FROM historico_clinico h WHERE h.id_paciente=pac.id AND h.tipo='alergia') AS alergias,
       (SELECT string_agg(h.descricao, ', ' ORDER BY h.id) FROM historico_clinico h WHERE h.id_paciente=pac.id AND h.tipo='medicamento') AS medicamentos_em_uso,
       (SELECT string_agg(h.descricao, ', ' ORDER BY h.id) FROM historico_clinico h WHERE h.id_paciente=pac.id AND h.tipo='condicao') AS doencas_preexistentes,
       pac.observacoes, initcap(pac.status::text) AS status, pac.criado_em::timestamp AS criado_em
FROM pacientes pac JOIN pessoa p ON p.id=pac.id_pessoa LEFT JOIN usuarios u ON u.id_pessoa=p.id
JOIN plano_saude pl ON pl.id=pac.id_plano LEFT JOIN vw_enderecos e ON e.id=pac.id_endereco;
CREATE VIEW vw_dentistas AS
SELECT d.id, u.id AS id_usuario, p.nome, p.email,
       (SELECT formatar_telefone(t.numero) FROM telefone t WHERE t.id_pessoa=p.id AND t.finalidade='principal') AS telefone,
       formatar_cpf(p.cpf) AS cpf, to_char(p.nascimento,'YYYY-MM-DD') AS nascimento,
       'CRO-' || d.cro_uf || ' ' || d.cro_numero AS cro, esp.nome AS especialidade,
       d.titulacao, d.faculdade, d.ano_formatura, to_char(d.admissao,'YYYY-MM-DD') AS admissao,
       d.cor, s.nome AS sala, initcap(d.status::text) AS status,
       ARRAY(SELECT DISTINCT to_char(hora,'HH24:MI') FROM disponibilidade_dentista WHERE id_dentista=d.id ORDER BY 1) AS horarios,
       ARRAY(SELECT ds.nome FROM dia_semana ds WHERE EXISTS (SELECT 1 FROM disponibilidade_dentista dd WHERE dd.id_dentista=d.id AND dd.id_dia_semana=ds.id) ORDER BY ds.id) AS dias_atendimento,
       ARRAY(SELECT pr.nome FROM procedimentos pr JOIN dentista_procedimentos dp ON dp.id_procedimento=pr.id WHERE dp.id_dentista=d.id ORDER BY pr.nome) AS procedimentos,
       (SELECT count(*) FROM agendamentos a WHERE a.id_dentista=d.id AND date_trunc('month',a.data)=date_trunc('month',CURRENT_DATE)) AS atendimentos_mes
FROM dentistas d JOIN pessoa p ON p.id=d.id_pessoa LEFT JOIN usuarios u ON u.id_pessoa=p.id
JOIN especialidade esp ON esp.id=d.id_especialidade LEFT JOIN sala s ON s.id=d.id_sala;
CREATE VIEW vw_procedimentos AS
SELECT p.id, p.nome, c.nome AS categoria, p.duracao_min, p.valor_base
FROM procedimentos p JOIN categoria_procedimento c ON c.id=p.id_categoria;
CREATE VIEW vw_agendamentos AS
SELECT a.id, a.id_paciente, a.id_dentista, pp.nome AS paciente, pd.nome AS dentista,
       pr.nome AS servico, to_char(a.data,'YYYY-MM-DD') AS data, to_char(a.hora,'HH24:MI') AS hora,
       s.nome AS sala, a.status::text AS status, a.valor, (pg.pago_em IS NOT NULL) AS pago,
       COALESCE(fp.nome, '') AS forma_pagamento, a.observacoes
FROM agendamentos a JOIN pacientes pac ON pac.id=a.id_paciente JOIN pessoa pp ON pp.id=pac.id_pessoa
JOIN dentistas d ON d.id=a.id_dentista JOIN pessoa pd ON pd.id=d.id_pessoa
JOIN procedimentos pr ON pr.id=a.id_procedimento JOIN sala s ON s.id=a.id_sala
LEFT JOIN pagamento pg ON pg.id_agendamento=a.id LEFT JOIN forma_pagamento fp ON fp.id=pg.id_forma_pagamento;
CREATE VIEW vw_clinica AS
SELECT c.id, c.nome, c.razao_social,
       regexp_replace(c.cnpj, '^([0-9]{2})([0-9]{3})([0-9]{3})([0-9]{4})([0-9]{2})$', '\1.\2.\3/\4-\5') AS cnpj,
       (SELECT formatar_telefone(t.numero) FROM telefone t WHERE t.id_clinica=c.id AND t.finalidade='principal') AS telefone,
       c.email, e.endereco, e.bairro, e.cidade, e.estado, e.cep, c.horario,
       c.logo_texto, c.cor_primaria, c.cor_destaque, c.limite_agendamentos_dia, c.antecedencia_min_dias,
       c.atualizado_em::timestamp AS atualizado_em
FROM clinica c LEFT JOIN vw_enderecos e ON e.id=c.id_endereco;
COMMIT;
