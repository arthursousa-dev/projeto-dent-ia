CREATE TABLE clinica (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id = 1),
    nome VARCHAR(150) NOT NULL, razao_social VARCHAR(200) NOT NULL,
    cnpj VARCHAR(14) NOT NULL CHECK (cnpj ~ '^[0-9]{14}$'),
    email VARCHAR(150) NOT NULL CHECK (email ~ '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'),
    id_endereco INT REFERENCES endereco ON DELETE RESTRICT,
    horario VARCHAR(200) NOT NULL, logo_texto VARCHAR(50) NOT NULL,
    cor_primaria VARCHAR(7) NOT NULL CHECK (cor_primaria ~ '^#[0-9A-Fa-f]{6}$'),
    cor_destaque VARCHAR(7) NOT NULL CHECK (cor_destaque ~ '^#[0-9A-Fa-f]{6}$'),
