    antecedencia_min_dias SMALLINT NOT NULL DEFAULT 1 CHECK (antecedencia_min_dias >= 0),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE telefone (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pessoa INT REFERENCES pessoa ON DELETE RESTRICT,
    id_clinica SMALLINT REFERENCES clinica ON DELETE RESTRICT,
    numero VARCHAR(11) NOT NULL CHECK (numero ~ '^[1-9][0-9]([2-5][0-9]{7}|9[0-9]{8})$'),
    finalidade finalidade_telefone NOT NULL,
    CHECK ((id_pessoa IS NOT NULL) <> (id_clinica IS NOT NULL)),
    UNIQUE (id_pessoa, numero), UNIQUE (id_clinica, numero)
);
CREATE UNIQUE INDEX telefone_principal_pessoa ON telefone (id_pessoa) WHERE finalidade = 'principal';
CREATE UNIQUE INDEX telefone_principal_clinica ON telefone (id_clinica) WHERE finalidade = 'principal';
